#!/usr/bin/env node
/* Regenerates the pages that come from course/scheme-of-work.json:
     index.html                  (home page, topic list)
     course/index.html           (course information)
     <topic-slug>/index.html     (outline page for every topic whose status is "outline")
   Topics whose status is "live" (hand-written pages, e.g. number/) are linked but never overwritten.
   Run:  node tools/build-site.js                                                              */
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const data = JSON.parse(fs.readFileSync(path.join(root, "course/scheme-of-work.json"), "utf8"));

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const write = (rel, html) => { const f = path.join(root, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, html); console.log("wrote", rel); };

function page({ title, depth, crumbs, body }) {
  const up = "../".repeat(depth);
  return `<!DOCTYPE html>
<!-- Generated by tools/build-site.js from course/scheme-of-work.json. Edit those, not this file. -->
<html lang="en-NZ">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} – Interactive Maths</title>
<link rel="stylesheet" href="${up}assets/style.css">
</head>
<body>
<header class="site"><a href="${up}index.html">Interactive Maths</a><div class="crumbs">${crumbs}</div></header>
<main>
${body}
</main>
</body>
</html>
`;
}

/* ---------- home ---------- */
{
  const items = data.topics.map((t) => {
    const meta = `${t.lessons} lessons · ${esc(t.weeks.split(".")[0])}`;
    if (t.status === "live") return `    <li><a class="l" href="${t.slug}/index.html"><strong>${t.n}. ${esc(t.title)}</strong><small>${meta}</small></a></li>`;
    return `    <li><a class="l" href="${t.slug}/index.html"><strong>${t.n}. ${esc(t.title)}</strong><small>${meta} · interactive lessons coming soon (outline available)</small></a></li>`;
  }).join("\n");
  write("index.html", page({
    title: "Year 10 Mathematics", depth: 0, crumbs: "Year 10 Mathematics 2027",
    body: `  <h1>Year 10 Mathematics</h1>
  <p class="lead">Short explanations, things to play with, and practice questions that mark themselves. Follows the 10MAY scheme of work (Cambridge IGCSE Core).</p>
  <ul class="lessons">
${items}
    <li><a class="l" href="course/index.html"><strong>Course information</strong><small>Timeline, common tests, command words, resources</small></a></li>
  </ul>`
  }));
}

/* ---------- course info ---------- */
{
  const c = data.course;
  const tl = data.timeline.map((r) => `<tr><td>T${r.term} W${r.week}</td><td>${esc(r.dates)}</td><td>${esc(r.topic)}</td><td>${esc(r.assessment)}</td></tr>`).join("\n");
  const ctw = data.commonTestWeeks;
  const mine = ctw.classes[ctw.thisClass];
  const tests = ctw.columns.map((col, i) => `<tr><td>${esc(col)}</td><td>${esc(mine[i])}</td></tr>`).join("\n");
  const cmd = data.commandWords.map(([w, m]) => `<tr><th scope="row">${esc(w)}</th><td>${esc(m)}</td></tr>`).join("\n");
  const sc = c.successCriteria.map((s) => `<h3>${esc(s.title)}</h3><ul>${s.points.map((p) => `<li>${esc(p)}</li>`).join("")}</ul>`).join("\n");
  const res = c.resources.map((r) => `<li><a href="${esc(r.url)}">${esc(r.name)}</a>: ${esc(r.what)}</li>`).join("\n");
  write("course/index.html", page({
    title: "Course information", depth: 1, crumbs: "Course information",
    body: `  <span class="tag">${esc(c.class)}</span>
  <h1>Course information</h1>
  <p class="lead">${esc(c.school)} · ${esc(c.title)} · revised ${esc(c.revised)}</p>
  <p>${esc(c.levels)}</p>

  <h2>Equipment</h2>
  <p>${esc(c.equipment)}</p>

  <h2>Textbooks and resources</h2>
  <ul>${c.textbooks.map((t) => `<li>${esc(t)}</li>`).join("")}</ul>
  <ul>${res}</ul>

  <h2>Timeline</h2>
  <p>${esc(c.note)}</p>
  <table class="t"><tr><th>Week</th><th>Dates</th><th>Topic</th><th>Assessment</th></tr>
${tl}
  </table>

  <h2>Common test weeks for ${esc(ctw.thisClass)}</h2>
  <table class="t"><tr><th>Test</th><th>When</th></tr>
${tests}
  </table>

  <h2>Command words</h2>
  <p>These words are used in assessments. Knowing what they ask for helps you answer the question that was set.</p>
  <table class="t"><tr><th>Command word</th><th>What it means</th></tr>
${cmd}
  </table>

  <h2>Success criteria</h2>
${sc}

  <h2>Aims</h2>
  <p>The aims of this course are to enable students to:</p>
  <ul>${c.aims.map((a) => `<li>${esc(a)}</li>`).join("")}</ul>

  <h2>Assessment</h2>
  <ul>${c.assessment.map((a) => `<li>${esc(a)}</li>`).join("")}</ul>`
  }));
}

/* ---------- topic outline pages ---------- */
data.topics.filter((t) => t.status === "outline").forEach((t) => {
  const groups = t.groups.map((g) => {
    const objs = g.objectives.map((ob) => {
      const lines = ob.objectives.map((x) => `<li>${esc(x)}</li>`).join("");
      const notes = (ob.notes || []).map((x) => `<li><em>${esc(x)}</em></li>`).join("");
      return `<div class="card"><span class="tag">${esc(ob.code)}</span>${ob.textbook ? ` <small>Textbook ${esc(ob.textbook)}</small>` : ""}<ul>${lines}${notes}</ul></div>`;
    }).join("\n");
    return `  <h2>${g.lessons} lesson${g.lessons > 1 ? "s" : ""}: ${esc(g.objectives.map((o) => o.code).join(", "))}</h2>\n${objs}`;
  }).join("\n");
  const prev = data.topics.find((x) => x.n === t.n - 1), next = data.topics.find((x) => x.n === t.n + 1);
  const nav = `<div class="nav">${prev ? `<a class="btn ghost" href="../${prev.slug}/index.html">‹ ${esc(prev.title)}</a>` : "<span></span>"}${next ? `<a class="btn ghost" href="../${next.slug}/index.html">${esc(next.title)} ›</a>` : ""}</div>`;
  write(`${t.slug}/index.html`, page({
    title: `Topic ${t.n}: ${t.title}`, depth: 1, crumbs: `Year 10 Mathematics 2027 › Topic ${t.n}: ${esc(t.title)}`,
    body: `  <span class="tag">Topic ${t.n}</span>
  <h1>${esc(t.title)}</h1>
  <p class="lead">${t.lessons} lessons${t.revision ? " + 1 revision session" : ""} · Assessment: ${esc(t.test)} · ${esc(t.weeks)}</p>
  <div class="key">The interactive lessons for this topic are still being built. This page shows what the course covers, taken from the handbook.</div>
${groups}
  ${nav}`
  }));
});

/* ---------- course/handbook.md (plain-text copy for reading in any Claude client) ---------- */
{
  const c = data.course;
  const L = [];
  L.push("# 10MAY Mathematics Course Handbook 2027 (structured copy)", "",
    "<!-- Generated by tools/build-site.js from course/scheme-of-work.json. Edit the JSON, not this file. -->", "",
    `${c.school} · ${c.class} · revised ${c.revised}. ${c.note}`, "", c.levels, "",
    "Textbook page numbers below are for **Cambridge IGCSE Core Mathematics 4th edition (Pimentel & Wall)**.", "",
    `Equipment: ${c.equipment}`, "", "## Timeline and tests", "",
    "| Week | Dates | Topic | Assessment |", "|---|---|---|---|");
  data.timeline.forEach((r) => { if (r.topic || r.assessment) L.push(`| T${r.term} W${r.week} | ${r.dates} | ${r.topic} | ${r.assessment} |`); });
  const ctw = data.commonTestWeeks;
  L.push("", `Common test weeks for ${ctw.thisClass}: ` + ctw.columns.map((col, i) => `${col} ${ctw.classes[ctw.thisClass][i]}`).join("; ") + ".", "",
    "## Command words", "", "| Word | Meaning |", "|---|---|");
  data.commandWords.forEach(([w, m]) => L.push(`| ${w} | ${m} |`));
  L.push("", "## Topics and learning objectives", "");
  data.topics.forEach((t) => {
    L.push(`### Topic ${t.n}: ${t.title}`, "", `${t.lessons} lessons${t.revision ? " + 1 revision session" : ""} · ${t.test} · ${t.weeks}`, "");
    t.groups.forEach((g) => {
      L.push(`**${g.lessons} lesson${g.lessons > 1 ? "s" : ""}** (${g.objectives.map((o) => o.code).join(", ")})`, "");
      g.objectives.forEach((ob) => {
        L.push(`- **${ob.code}**${ob.textbook ? ` (textbook ${ob.textbook})` : ""}`);
        ob.objectives.forEach((x) => L.push(`  - ${x}`));
        (ob.notes || []).forEach((x) => L.push(`  - *Note:* ${x}`));
      });
      L.push("");
    });
  });
  L.push("## Core syllabus code to textbook page map", "");
  Object.keys(data.coreSyllabusPages).forEach((k) => {
    L.push(`**${k}**`, "", "| Code | Topic | Pages |", "|---|---|---|");
    data.coreSyllabusPages[k].forEach(([a, b, p]) => L.push(`| ${a} | ${b} | ${p} |`));
    L.push("");
  });
  L.push("## Success criteria", "");
  c.successCriteria.forEach((s) => { L.push(`**${s.title}**`, ""); s.points.forEach((p) => L.push(`- ${p}`)); L.push(""); });
  L.push("## Notes on the source", "",
    "- Where the handbook merges table cells, the lesson count belongs to the whole group of objectives, as shown above.",
    "- The handbook says \"novation\" of Venn diagrams under 1.2; this is a typo for \"notation\" and is corrected here.",
    "- Objective codes in Topics 4–11 follow the Cambridge syllabus numbering (2.7, 2.10, 2.11, 4.x, 5.x, 6.x, 7.x), not the topic number.",
    "- The Extended (E) syllabus tables in the handbook are not reproduced; this course follows Core.",
    "- Google Drive links for the textbook, past tests and syllabus are in the original PDF and deliberately not copied here.", "");
  write("course/handbook.md", L.join("\n"));
}
